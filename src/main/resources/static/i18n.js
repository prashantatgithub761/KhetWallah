    const originals = new WeakMap();
    const storageKey = "khetwallah-language";
    let language = "en";
    try { language = localStorage.getItem(storageKey) === "hi" ? "hi" : "en"; } catch (_) { /* Private mode can disable storage. */ }
    function t(key, params = {}) {
        const template = language === "hi" ? (hi[key] || en[key] || key) : (en[key] || key);
        return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) =>
            Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
    }
    function updateElement(element) {
        let params = {};
        try { const value = JSON.parse(element.dataset.i18nParams || "{}"); if (value && typeof value === "object" && !Array.isArray(value)) params = value; } catch (_) {}
        const key = element.getAttribute("data-i18n");
        if (key) {
            // A translated label may also contain an input, icon or timestamp. Keep these nodes intact.
            if (element.childElementCount === 0) element.textContent = t(key, params);
            else {
                const copy = Array.from(element.childNodes).find(node => node.nodeType === Node.TEXT_NODE && node.textContent.trim());
                if (copy) copy.textContent = t(key, params);
            }
        }
        for (const attribute of ["placeholder", "aria-label", "title"]) {
            const value = element.getAttribute(`data-i18n-${attribute}`);
            if (value) element.setAttribute(attribute, t(value, params));
        }
    }
    function apply(root = document) {
        if (root.nodeType === 1) updateElement(root);
        root.querySelectorAll?.("[data-i18n], [data-i18n-placeholder], [data-i18n-aria-label], [data-i18n-title]").forEach(updateElement);
    }
    // Translate only known static copy captured at initial load. Dynamic user data must never be captured.
    const capturedText = [];
    const capturedAttributes = [];
    function captureStaticCopy() {
        const excluded = "script,style,code,pre,textarea,[role=status],[data-i18n],[data-i18n-skip],#listings,#orders,#pickup-list,#listing-content,#account-heading,#account-intro";
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            if (node.parentElement?.closest(excluded)) continue;
            const original = node.textContent;
            const key = original.trim();
            if (Object.prototype.hasOwnProperty.call(hi, key)) {
                originals.set(node, original);
                capturedText.push({node, key});
            }
        }
        document.querySelectorAll("input[placeholder],textarea[placeholder],[aria-label]").forEach(element => {
            if (element.closest("[data-i18n-skip]")) return;
            for (const attribute of ["placeholder", "aria-label"]) {
                const key = element.getAttribute(attribute);
                if (key && Object.prototype.hasOwnProperty.call(hi, key)
                        && !element.hasAttribute(`data-i18n-${attribute}`)) capturedAttributes.push({element, attribute, key});
            }
        });
    }
    function refresh() {
        document.documentElement.lang = language;
        for (const {node, key} of capturedText) {
            if (!node.isConnected) continue;
            const original = originals.get(node);
            node.textContent = original.replace(key, t(key));
        }
        for (const {element, attribute, key} of capturedAttributes) element.setAttribute(attribute, t(key));
        apply();
        document.querySelectorAll("[data-language-option]").forEach(button => {
            const selected = button.dataset.languageOption === language;
            button.setAttribute("aria-pressed", String(selected));
            button.classList.toggle("selected", selected);
        });
    }
    function setLanguage(value) {
        if (value !== "en" && value !== "hi") return;
        if (value === language) return;
        language = value;
        try { localStorage.setItem(storageKey, value); } catch (_) {}
        refresh();
        document.dispatchEvent(new CustomEvent("khet:languagechange", {detail:{language}}));
        window.dispatchEvent(new CustomEvent("languagechange", {detail:{language}}));
    }
    function initialise() {
        captureStaticCopy();
        const header = document.querySelector(".header-content") || document.querySelector("header");
        if (header && !document.getElementById("language-switcher")) {
            const control = document.createElement("div");
            control.id = "language-switcher";
            control.className = "language-switcher";
            control.setAttribute("role", "group");
            control.setAttribute("aria-label", "Language / भाषा");
            for (const [code, label] of [["en", "English"], ["hi", "हिन्दी"]]) {
                const button = document.createElement("button");
                button.type = "button";
                button.className = "secondary language-option";
                button.dataset.languageOption = code;
                button.lang = code;
                button.textContent = label;
                button.addEventListener("click", () => setLanguage(code));
                control.appendChild(button);
            }
            header.appendChild(control);
        }
        refresh();
    }
    window.KhetI18n = Object.freeze({t, apply, setLanguage, get language() { return language; },
        get locale() { return language === "hi" ? "hi-IN" : "en-IN"; }});
    if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", initialise, {once:true});
    else initialise();
